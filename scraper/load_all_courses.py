# ── yt-dlp helpers ────────────────────────────────────────────────────────────

def yt_info(playlist_id: str, timeout: int = 30) -> Optional[dict]:
    """Fetch playlist metadata using yt-dlp (no download)."""
    ydl_opts = {
        "quiet": True,
        "no_warnings": True,
        "extract_flat": True,
        "ignoreerrors": True,
        "socket_timeout": timeout,
        "retries": 2,
    }
    url = f"https://www.youtube.com/playlist?list={playlist_id}"
    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(url, download=False)
        if info is None:
            return None
        entries = [e for e in (info.get("entries") or []) if e]
        first_vid = entries[0].get("id") if entries else None
        return {
            "video_count": len(entries),
            "first_video_id": first_vid,
            "thumbnail_url": (
                f"https://i.ytimg.com/vi/{first_vid}/hqdefault.jpg"
                if first_vid else None
            ),
            "title": info.get("title", ""),
        }
    except Exception as exc:
        print(f"  [yt-dlp FAIL] {playlist_id}: {exc}", flush=True)
        return None


def enrich_course(course: dict) -> dict:
    """Attach real video_count and thumbnail_url to a course dict via yt-dlp."""
    pid = course.get("playlist_id")
    if not pid:
        return course
    time.sleep(DELAY)
    info = yt_info(pid)
    if info:
        course["video_count"] = info["video_count"]
        course["thumbnail_url"] = info.get("thumbnail_url")
    return course


