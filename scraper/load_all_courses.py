def upsert_university(cur, uni: dict) -> str:
    """Insert or update a university and return its UUID id."""
    uni_id = str(uuid.uuid4())
    cur.execute(
        """
        INSERT INTO universities (id, name, slug, website, country, description, source_key)
        VALUES (%s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (slug) DO UPDATE SET
            name        = EXCLUDED.name,
            website     = EXCLUDED.website,
            country     = EXCLUDED.country,
            description = EXCLUDED.description
        RETURNING id
        """,
        (
            uni_id,
            uni["name"],
            uni["slug"],
            uni.get("website"),
            uni.get("country"),
            uni.get("description"),
            uni.get("source_key", uni["slug"]),
        ),
    )
    row = cur.fetchone()
    return str(row[0])


def upsert_department(cur, name: str, uni_id: str) -> str:
    dept_slug = slugify(f"{name}")
    dept_id = str(uuid.uuid4())
    cur.execute(
        """
        INSERT INTO departments (id, name, slug, university_id)
        VALUES (%s, %s, %s, %s)
        ON CONFLICT DO NOTHING
        RETURNING id
        """,
        (dept_id, name, dept_slug, uni_id),
    )
    row = cur.fetchone()
    if row:
        return str(row[0])
    # Fetch existing
    cur.execute(
        "SELECT id FROM departments WHERE slug = %s AND university_id = %s",
        (dept_slug, uni_id),
    )
    row = cur.fetchone()
    return str(row[0]) if row else dept_id


def upsert_subject(cur, name: str) -> str:
    subj_slug = slugify(name)
    subj_id = str(uuid.uuid4())
    cur.execute(
        """
        INSERT INTO subjects (id, name, slug)
        VALUES (%s, %s, %s)
        ON CONFLICT (slug) DO NOTHING
        RETURNING id
        """,
        (subj_id, name, subj_slug),
    )
    row = cur.fetchone()
    if row:
        return str(row[0])
    cur.execute("SELECT id FROM subjects WHERE slug = %s", (subj_slug,))
    row = cur.fetchone()
    return str(row[0]) if row else subj_id


LEVEL_MAP = {
    "undergraduate": "undergraduate",
    "graduate": "graduate",
    "professional": "professional",
}


def make_slug(title: str, source: str, seen: set) -> str:
    base = slugify(f"{title} {source}")
    slug = base
    counter = 2
    while slug in seen:
        slug = f"{base}-{counter}"
        counter += 1
    seen.add(slug)
    return slug


def insert_course(cur, course: dict, uni_id: str, dept_id: str, slug: str) -> Optional[str]:
    """Insert a course and return its UUID, or None on conflict."""
    course_id = str(uuid.uuid4())
    level_raw = course.get("level", "other")
    level = LEVEL_MAP.get(level_raw, "other")

    try:
        cur.execute(
            """
            INSERT INTO courses (
                id, title, slug, level, source_key, source_url,
                thumbnail_url, instructor, year, semester,
                has_video_lectures, total_videos, youtube_playlist_id,
                university_id, department_id, course_number, description
            ) VALUES (
                %s, %s, %s, %s::courselevel, %s, %s,
                %s, %s, %s, %s,
                %s, %s, %s,
                %s, %s, %s, %s
            )
            ON CONFLICT (slug) DO UPDATE SET
                thumbnail_url       = COALESCE(EXCLUDED.thumbnail_url, courses.thumbnail_url),
                total_videos        = GREATEST(EXCLUDED.total_videos, courses.total_videos),
                has_video_lectures  = EXCLUDED.has_video_lectures OR courses.has_video_lectures,
                youtube_playlist_id = COALESCE(EXCLUDED.youtube_playlist_id, courses.youtube_playlist_id),
                description         = COALESCE(EXCLUDED.description, courses.description)
            RETURNING id
            """,
            (
                course_id,
                course["title"],
                slug,
                level,
                course.get("source_key", "unknown"),
                course.get("source_url", ""),
                course.get("thumbnail_url"),
                course.get("instructor"),
                course.get("year"),
                course.get("semester"),
                bool(course.get("playlist_id")),
                course.get("video_count", 0),
                course.get("playlist_id"),
                uni_id,
                dept_id,
                course.get("course_number"),
                course.get("description"),
            ),
        )
        row = cur.fetchone()
        return str(row[0]) if row else None
    except Exception as exc:
        print(f"  [DB WARN] {course['title']}: {exc}", flush=True)
        return None


def link_subjects(cur, course_id: str, subjects: list[str]) -> None:
    for name in subjects:
        if not name:
            continue
        subj_id = upsert_subject(cur, name)
        cur.execute(
            """
            INSERT INTO course_subjects (course_id, subject_id)
            VALUES (%s, %s) ON CONFLICT DO NOTHING
            """,
            (course_id, subj_id),
        )


# ── Main ─────────────────────────────────────────────────────────────────────

def main():
    print("=" * 60, flush=True)
    print("OpenCourseWare Comprehensive Loader", flush=True)
    print("=" * 60, flush=True)

    # ── Step 1: Enrich all courses via yt-dlp in parallel ─────────────────
    all_courses_flat: list[tuple[str, dict]] = []  # (uni_key, course)
    for uni_key, uni_data in CATALOGUE.items():
        for c in uni_data["courses"]:
            c["source_key"] = uni_data.get("source_key", uni_key)
            all_courses_flat.append((uni_key, c))

    total = len(all_courses_flat)
    print(f"\nEnriching {total} courses via yt-dlp ({WORKERS} workers)...", flush=True)

    enriched: dict[int, dict] = {}
    done = 0

    with ThreadPoolExecutor(max_workers=WORKERS) as executor:
        futures = {
            executor.submit(enrich_course, c): i
            for i, (_, c) in enumerate(all_courses_flat)
        }
        for future in as_completed(futures):
            idx = futures[future]
            try:
                enriched[idx] = future.result()
            except Exception as exc:
                _, c = all_courses_flat[idx]
                enriched[idx] = c
                print(f"  [WARN] {c.get('title')}: {exc}", flush=True)
            done += 1
            if done % 10 == 0 or done == total:
                print(f"  Progress: {done}/{total}", flush=True)

    # ── Step 2: Write to database ─────────────────────────────────────────
    print("\nConnecting to database...", flush=True)
    conn = connect()
    cur = conn.cursor()
    print("Connected!", flush=True)

    seen_slugs: set[str] = set()
    # Pre-load existing slugs to avoid collisions
    cur.execute("SELECT slug FROM courses")
    for (s,) in cur.fetchall():
        seen_slugs.add(s)

    stats = {"universities": 0, "departments": 0, "courses_inserted": 0, "courses_updated": 0, "skipped": 0}

    for uni_key, uni_data in CATALOGUE.items():
        print(f"\n→ {uni_data['name']} ({len(uni_data['courses'])} courses)", flush=True)

        uni_id = upsert_university(cur, uni_data)
        conn.commit()
        stats["universities"] += 1

        dept_cache: dict[str, str] = {}
        idx_offset = sum(len(CATALOGUE[k]["courses"]) for k in list(CATALOGUE.keys())[:list(CATALOGUE.keys()).index(uni_key)])

        for local_i, course in enumerate(uni_data["courses"]):
            global_i = idx_offset + local_i
            course = enriched.get(global_i, course)

            dept_name = course.get("dept", "General")
            if dept_name not in dept_cache:
                dept_cache[dept_name] = upsert_department(cur, dept_name, uni_id)
            dept_id = dept_cache[dept_name]

            slug = make_slug(course["title"], uni_data["slug"], seen_slugs)
            c_id = insert_course(cur, course, uni_id, dept_id, slug)

            if c_id:
                link_subjects(cur, c_id, course.get("subjects", []))
                print(
                    f"   ✓ {course['title'][:55]:<55} | {course.get('video_count', 0):>3} videos | {course.get('thumbnail_url', 'no thumb')[:30]}",
                    flush=True,
                )
                stats["courses_inserted"] += 1
            else:
                stats["skipped"] += 1

        conn.commit()

    cur.close()
    conn.close()

    print("\n" + "=" * 60, flush=True)
    print("DONE!", flush=True)
    print(f"  Universities : {stats['universities']}", flush=True)
    print(f"  Courses inserted/updated : {stats['courses_inserted']}", flush=True)
    print(f"  Skipped      : {stats['skipped']}", flush=True)
    print("=" * 60, flush=True)


if __name__ == "__main__":
    main()
